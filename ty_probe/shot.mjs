import fs from 'node:fs';
const PORT = 9333;
const SRC = fs.readFileSync('../tiaoyue-ref-helper.user.js', 'utf8');
const list = await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json();
const page = list.find(t => t.type === 'page');
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pend = new Map();
const send = (m, p = {}) => new Promise((res, rej) => { const i = ++id; pend.set(i, { res, rej }); ws.send(JSON.stringify({ id: i, method: m, params: p })); setTimeout(() => { if (pend.has(i)) { pend.delete(i); rej(new Error('timeout ' + m)); } }, 8000); });
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { const p = pend.get(m.id); pend.delete(m.id); m.error ? p.rej(new Error(JSON.stringify(m.error))) : p.res(m.result); } };
await new Promise(r => ws.onopen = r);
await send('Emulation.setDeviceMetricsOverride', { width: 900, height: 760, deviceScaleFactor: 2, mobile: false });
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const ev = async (x) => { const r = await send('Runtime.evaluate', { expression: x, returnByValue: true }); if (r.exceptionDetails) throw new Error(r.exceptionDetails.exception?.description); return r.result.value; };
await send('Page.navigate', { url: 'http://127.0.0.1:8765/fake2.html' });
await sleep(900);
await ev(`localStorage.setItem('tyq.guide.v1','true');localStorage.removeItem('tyq.panel.pos.v1');'ok'`);
await ev(SRC + '\n"ok"');
await sleep(1660);
await ev('__TYQ.open("asset"); 1');
await sleep(700);
const shot = await send('Page.captureScreenshot', { format: 'png' });
fs.writeFileSync('../panel-1.3.0.png', Buffer.from(shot.data, 'base64'));
console.log('shot ok');
process.exit(0);
